/** All site polygons (rotunda first). */
export const SITE: V2[][] = [ROTUNDA, ...WINGS];

export function insidePoly(p: V2[], x: number, z: number): boolean {
    let inside = false;
    for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
        const [xi, zi] = p[i]!;
        const [xj, zj] = p[j]!;
        if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) inside = !inside;
    }
    return inside;
}

/** Horizontal distance (m) from (x, z) to the site (0 inside any polygon). */
export function siteDistance(x: number, z: number): number {
    let best = Infinity;
    for (const p of SITE) {
        if (insidePoly(p, x, z)) return 0;
        for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
            const [ax, az] = p[j]!;
            const [bx, bz] = p[i]!;
            const dx = bx - ax;
            const dz = bz - az;
            const t = Math.max(0, Math.min(1, ((x - ax) * dx + (z - az) * dz) / (dx * dx + dz * dz || 1)));
            best = Math.min(best, Math.hypot(ax + dx * t - x, az + dz * t - z));
        }
    }
    return best;
}
